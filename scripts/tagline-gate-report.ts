/**
 * Runs the tagline shape gate and writes `_agent/tagline-gate-report.md`.
 * Run: node --import tsx scripts/tagline-gate-report.ts
 */
import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { loadFontMetrics } from "@/lib/landing/font-metrics"
import {
  clampPx,
  heroTextWidth,
  HERO_BREAKPOINTS,
  HERO_FONT,
  HERO_HEADLINE_CLAMP,
  HERO_SUBLINE_CLAMP,
} from "@/lib/landing/hero-type"
import { HERO_VARIANT_IDS } from "@/lib/landing/hero-experiment"
import {
  experimentCandidates,
  HEADLINE_RULES,
  runTaglineGate,
  SUBLINE_RULES,
  type BreakpointResult,
} from "@/lib/landing/tagline-gate"
import { parseMarkedText, renderAscii } from "@/lib/landing/tagline-shape"

const results = runTaglineGate()
const chosen = experimentCandidates(results)
const font = loadFontMetrics(
  fileURLToPath(new URL(`../${HERO_FONT.file}`, import.meta.url))
)

const part = (
  breakpoint: BreakpointResult,
  which: "headline" | "subline"
): string => {
  const result = breakpoint[which]
  const fontPx =
    which === "headline" ? breakpoint.headlineFontPx : breakpoint.sublineFontPx
  const head = `${which} @ ${breakpoint.viewport}px (container ${breakpoint.containerPx}px, ${fontPx.toFixed(2)}px type): ${result.pass ? "PASS" : "FAIL"}`
  const shape = `shape ${result.chosen.shape}, longest/shortest ${result.chosen.ratio.toFixed(2)}, ${result.chosen.lines.length} line${result.chosen.lines.length === 1 ? "" : "s"}, breaks after chunk ${result.chosen.breaks.length ? result.chosen.breaks.join(", ") : "none"}`
  const reasons = result.pass
    ? `best of ${result.evaluated} break sets`
    : `no break set passes (${result.evaluated} tried). Closest fails: ${result.chosen.reasons.join(", ")}. Rejections by rule: ${JSON.stringify(result.rejectedBy)}`
  return `${head}\n  ${shape}\n  ${reasons}\n${renderAscii(result.chosen, breakpoint.containerPx)}`
}

const stress = (id: string): string => {
  const entry = chosen.find((result) => result.candidate.id === id)
  if (!entry) return ""
  const small = entry.breakpoints[0]!
  const headlinePx = clampPx(HERO_HEADLINE_CLAMP, 320)
  const sublinePx = clampPx(HERO_SUBLINE_CLAMP, 320)
  const box = heroTextWidth(320)
  const widest = (lines: readonly { text: string }[], px: number) =>
    Math.max(...lines.map((line) => font.width(line.text, px)))
  const h = widest(small.headline.chosen.lines, headlinePx)
  const s = widest(small.subline.chosen.lines, sublinePx)
  return `- ${id}: widest headline line ${Math.round(h)}px, widest subline line ${Math.round(s)}px in a ${box}px box: ${h <= box && s <= box ? "fits" : "overflows (wraps to an extra line; text-wrap: balance keeps it tidy)"}`
}

const lines: string[] = []
const push = (text = "") => lines.push(text)

push("# Tagline shape gate report")
push()
push(
  `Generated by \`scripts/tagline-gate-report.ts\`. Rules and thresholds live in \`lib/landing/tagline-shape.ts\` and \`lib/landing/tagline-gate.ts\`; \`lib/landing/hero-variants.test.ts\` re-runs the gate on every \`pnpm test\`.`
)
push()
push("## Result")
push()
push(
  `${results.length} candidates drafted, ${results.filter((r) => r.pass).length} pass, ${chosen.length} go into the A/B test (first three passing, in draft order).`
)
push()
push("| Candidate | Angle | Gate | In test |")
push("| --- | --- | --- | --- |")
for (const result of results) {
  const inTest = (HERO_VARIANT_IDS as readonly string[]).includes(
    result.candidate.id
  )
  push(
    `| ${result.candidate.id} | ${result.candidate.angle} | ${result.pass ? "PASS" : "FAIL"} | ${inTest ? "yes" : "no"} |`
  )
}
push()
push("## How the measuring works")
push()
push(
  '- Wanted: `@chenglou/pretext` (as used in `~/dev/nextjs/mangles`, read only). It could not be used: `pnpm add` is blocked in the agent sandbox (the npm registry is denied and the pnpm store is outside the writable area), and pretext throws "Text measurement requires OffscreenCanvas or a DOM canvas context" under Node anyway.'
)
push(
  `- Fallback, as the brief allows: advance widths read straight from the shipped font file, \`${HERO_FONT.file}\` (Hammersmith One, ${HERO_FONT.weight}, tracking ${HERO_FONT.trackingEm}em), by a small TrueType reader (\`lib/landing/font-metrics.ts\`: \`cmap\` + \`hmtx\`). Hammersmith One has no \`kern\` or \`GPOS\` table (checked: only GDEF), so advances are the whole story and the numbers should match a browser to well under a pixel. The checker takes any \`(text) => width\` function, so pretext can be dropped in later.`
)
push(
  "- Type is the real hero type. `lib/landing/hero-type.ts` holds the clamp, leading, container (`max-w-xl`, `px-4`) and font; `lib/landing/hero-type.test.ts` reads `landing-fold-copy.tsx` and `app/globals.css` and fails if they drift."
)
push("- Widths measured: the hero text box, not the viewport.")
push()
push("| Viewport | Text box | Headline type | Subline type |")
push("| --- | --- | --- | --- |")
for (const { viewport } of HERO_BREAKPOINTS) {
  push(
    `| ${viewport}px | ${heroTextWidth(viewport)}px | ${clampPx(HERO_HEADLINE_CLAMP, viewport).toFixed(2)}px / 1.15 | ${clampPx(HERO_SUBLINE_CLAMP, viewport).toFixed(2)}px / 1.35 |`
  )
}
push()
push(
  "Tailwind switches: base (under 768), `md` (768 up), `lg` (1024 up). 768 and 1440 share a 544px box, but 1440 has the 28px cap on the type, so both are checked."
)
push()
push("## Rules")
push()
push(
  "Copy is marked up in `lib/landing/hero-candidates.ts`: spaces separate chunks, `{...}` glues words into one phrase unit that can never be broken. A line break may only fall between chunks, and the checker enumerates every set of up to two breaks (so one to three lines) per breakpoint and picks the best passing set."
)
push()
push("| Rule | Headline | Subline | Why |")
push("| --- | --- | --- | --- |")
const h = HEADLINE_RULES.sm
const s = SUBLINE_RULES.sm
push(
  `| Lines | 1 to ${h.maxLines} (prefers 2 to 3 on phone, 1 to 2 from md) | same | Brief. Chrome's own guidance caps balanced headings at six lines; three is already a lot for a hero. |`
)
push(
  `| Fit | every line within ${Math.round(h.fitShare * 100)}% of the text box | same | Headroom for hinting and font fallback. |`
)
push(
  `| Single word last line | fail | fail | A widow, "a graphic misdemeanor" (MyFonts, Fonts.com). |`
)
push(
  `| Longest / shortest line | at most ${h.maxRatio} | at most ${s.maxRatio} | Display type is read as a unit, so the shortest line must be at least half the longest. Running text tolerates a last line of about a third of the measure, so the subline allows 3. |`
)
push(
  `| Shape | balanced (within ${h.balancedRatio}x), long-short, long-short-long, short-long, short-short-long, long-short-short | same | Brief's good shapes. Short-long-short (a bulge) and any long-then-runt are rejected. |`
)
push(
  `| Phrase units | never split a group; a line may not end on an article, determiner, possessive, preposition, conjunction or "to" | same | Fonts.com "Breaking for sense": keep phrases together, pair adjectives with nouns, break where a reader would pause. The function-word list backs up groups an author forgot to mark. |`
)
push(
  `| Ranking | fewest soft misses (preferred line count), then shape rank, then lowest ratio, then fewer lines | same | Deterministic: ties fall back to the break list. |`
)
push()
push("## Sources")
push()
push(
  "- Fonts.com Fontology, [Breaking for Sense](https://www.myfonts.com/pages/fontscom-learning-fontology-level-4-fine-typography-breaking-for-sense): keep important phrases together, break after punctuation, pair adjectives with their nouns, keep names whole, break where a reader would pause aloud, avoid widows."
)
push(
  "- Fonts.com Learning, [Headline Line Breaks](https://www.fonts.com/content/learning/fyti/typographic-tips/headline-breaks): review every headline by hand and break for sense and for balance, avoiding both widows and radically uneven lines."
)
push(
  '- MyFonts, [Rags, Widows and Orphans](https://cms.myfonts.com/content/the-font-manual/rags-windows-orphans): a good rag has small line-to-line variation; large fluctuations distract; widows are a "graphic misdemeanor". It also warns that manual breaks in interactive copy are risky because browsers give little control, which is why breaks here are per breakpoint, measured, and backed by `text-wrap: balance`.'
)
push(
  "- Chrome for Developers, [CSS text-wrap: balance](https://developer.chrome.com/docs/css-ui/css-text-wrap-balance) (CSS Text Level 4): headlines are the primary use case, balancing only applies to blocks of six lines or fewer, and it needs a constrained width. Used here only as the fallback for widths the gate did not measure."
)
push()
push(
  "Not used: Bringhurst's *Elements of Typographic Style* and Butterick's *Practical Typography*. I could not verify what they say about headline breaks from the pages available, so the thresholds above are stated as this project's choices and not attributed to them."
)
push()
push("## Known gaps")
push()
push(
  '- **P22 Underground is probably what most visitors see.** The privacy page says the site loads it from Adobe Fonts. When `NEXT_PUBLIC_ADOBE_FONTS_KIT_ID` is set and the visitor has not opted out, the site swaps to the licensed Typekit face with weight 600 and -0.025em tracking (`html[data-tfl-type-profile="johnston-compatible"]`). It cannot be read offline, so the gate measures the Hammersmith One fallback (the default when no kit is set, and the opt-out face). I expect it to be narrower than Hammersmith One, which would only shorten lines (shapes hold because the breaks are explicit), but I have not verified that. If it is wider, lines could overflow; check on a device with the kit enabled.'
)
push(
  "- **320px phones.** Not a gated width. Stress check of the three variants' phone breaks at 320px:"
)
for (const id of HERO_VARIANT_IDS) push(stress(id))
push()
push("## Every candidate")
push()
for (const result of results) {
  push(
    `### ${result.candidate.id} · ${result.candidate.angle} · ${result.pass ? "PASS" : "FAIL"}`
  )
  push()
  push("```")
  push(
    `headline: ${parseMarkedText(result.candidate.headline)
      .map((c) => c.text)
      .join(" ")}`
  )
  push(
    `subline:  ${parseMarkedText(result.candidate.subline)
      .map((c) => c.text)
      .join(" ")}`
  )
  push("```")
  push()
  for (const breakpoint of result.breakpoints) {
    push("```")
    push(part(breakpoint, "headline"))
    push()
    push(part(breakpoint, "subline"))
    push("```")
    push()
  }
}

writeFileSync(
  fileURLToPath(new URL("../_agent/tagline-gate-report.md", import.meta.url)),
  `${lines.join("\n")}\n`
)
console.log(
  `wrote _agent/tagline-gate-report.md (${results.length} candidates, ${chosen.length} in test)`
)
