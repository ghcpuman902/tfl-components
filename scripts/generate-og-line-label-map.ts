/**
 * Pre-compute OG chip labels from LineName tiers (full → middle → short)
 * at the exact chip text budgets the live OG uses. Takumi then looks up —
 * no ellipsis, no runtime measuring.
 *
 * Run: pnpm exec tsx scripts/generate-og-line-label-map.ts
 */
import { createRequire } from "node:module"
import { readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { Renderer } from "@takumi-rs/core"
import { LINE_NAME_TIERS } from "../lib/tfl/line-names"

const require = createRequire(import.meta.url)
const helpersRoot = join(
  process.cwd(),
  "node_modules/.pnpm/@takumi-rs+helpers@2.16.2_react@19.3.1/node_modules/@takumi-rs/helpers/dist/index.cjs"
)
const { container, text } = require(helpersRoot) as {
  container: (p: object) => object
  text: (p: object) => object
}

/** Must match `components/og/board-share-live-og-image.tsx` chip slots. */
export const OG_LINE_LABEL_SLOTS = {
  /** B status / next-train chips: STATUS_CHIP_W − horizontal pad. */
  status: { width: 300, padX: 16, size: 32 },
  /** A "Also here" chips: typical max before fitChips drops the rest. */
  also: { width: 200, padX: 20, size: 28 },
} as const

export type OgLineLabelSlot = keyof typeof OG_LINE_LABEL_SLOTS

const fontPath = join(
  process.cwd(),
  "assets/fonts/hammersmith-one/HammersmithOne-Regular.ttf"
)

const measureWidth = async (
  renderer: Renderer,
  label: string,
  size: number
): Promise<number> => {
  const node = container({
    style: {
      display: "flex",
      fontFamily: "Hammersmith One",
      fontSize: size,
      lineHeight: 1,
      width: "max-content",
    },
    children: [text({ text: label })],
  })
  const measured = await renderer.measure(node, { width: 4000, height: 200 })
  return measured.width
}

export const pickOgLineLabel = async (
  renderer: Renderer,
  lineId: string,
  slot: OgLineLabelSlot
): Promise<string> => {
  const tiers = LINE_NAME_TIERS[lineId]
  if (!tiers) return lineId
  const { width, padX, size } = OG_LINE_LABEL_SLOTS[slot]
  const budget = width - padX * 2
  for (const label of [tiers.full, tiers.middle, tiers.short]) {
    if ((await measureWidth(renderer, label, size)) <= budget) return label
  }
  return tiers.short
}

const main = async () => {
  const renderer = new Renderer()
  await renderer.registerFont({
    data: readFileSync(fontPath),
    name: "Hammersmith One",
    weight: 400,
    style: "normal",
  })

  const status: Record<string, string> = {}
  const also: Record<string, string> = {}
  for (const id of Object.keys(LINE_NAME_TIERS).sort()) {
    status[id] = await pickOgLineLabel(renderer, id, "status")
    also[id] = await pickOgLineLabel(renderer, id, "also")
  }

  const outPath = join(process.cwd(), "lib/og/line-label-map.ts")
  const body = `/**
 * Static OG chip labels by LineName tier at fixed OG slot widths.
 * Generated by \`scripts/generate-og-line-label-map.ts\` — do not edit by hand.
 * \`lib/og/line-label-map.test.ts\` fails if this drifts from the generator.
 */

export type OgLineLabelSlot = "status" | "also"

export const OG_LINE_LABEL_MAP: Record<
  OgLineLabelSlot,
  Readonly<Record<string, string>>
> = {
  status: ${JSON.stringify(status, null, 2).replace(/\n/g, "\n  ")},
  also: ${JSON.stringify(also, null, 2).replace(/\n/g, "\n  ")},
} as const

/** Lookup for Takumi chips — falls back to the id when unknown. */
export const ogLineLabel = (
  lineId: string,
  slot: OgLineLabelSlot
): string => OG_LINE_LABEL_MAP[slot][lineId] ?? lineId
`
  writeFileSync(outPath, body)
  console.log("wrote", outPath, Object.keys(status).length, "lines")
}

const isDirect =
  process.argv[1] &&
  (process.argv[1].endsWith("generate-og-line-label-map.ts") ||
    process.argv[1].endsWith("generate-og-line-label-map"))

if (isDirect) {
  void main()
}
